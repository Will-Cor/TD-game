export function getCombinedTowerType(a: TowerType, b: TowerType): SuperTowerType | null {
  if (!isBaseTowerType(a) || !isBaseTowerType(b)) return null;
  const key = [a, b].sort().join('+');
  return COMBO_TABLE[key] ?? null;
}

