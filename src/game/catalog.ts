export function getLevelDef(level: number): LevelDef {
  const clamped = Math.max(1, Math.min(MAX_LEVEL, Math.round(level)));
  return LEVEL_DEFS[clamped - 1];
}

export function rollRandomLevelModifiers(level: number, seed: number): ModifierId[] {
  const def = getLevelDef(level);
  if (def.randomModifierCount <= 0) return [];
  const pool = MODIFIERS.map((m) => m.id);
  let s = ((seed >>> 0) ^ Math.imul(level, 0x9e3779b1)) >>> 0;
  for (let i = pool.length - 1; i > 0; i--) {
    s = (Math.imul(1664525, s) + 1013904223) >>> 0;
    const j = s % (i + 1);
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, def.randomModifierCount);
}

